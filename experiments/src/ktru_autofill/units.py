_PREPOSITIONS = {"в", "с", "к", "о", "у", "и", "а"}


def unit_key(written: str) -> str:
    """«Листов.» → «лист», «г/м²» → «г/м2», «″» → «"»."""
    u = written.strip().lower().replace("²", "2").replace("³", "3").replace("″", '"').replace(" ", "")
    u = u.rstrip(".").replace("ё", "е")
    u = u.replace("-", "")
    if "/" in u or not u.isalpha():
        return u.replace(".", "") if "/" in u else u
    return _parse(u)[0]


@lru_cache(maxsize=1)
def _registry() -> tuple[dict[str, Unit], dict[str, Unit]]:
    by_key: dict[str, Unit] = {}
    by_name: dict[str, Unit] = {}
    for name, dim, factor, spellings in _UNITS:
        unit = Unit(name, dim, factor)
        by_name[name] = unit
        for s in [name, *spellings]:
            key = unit_key(s)
            if key not in _PREPOSITIONS:  # «3 в 1», «2 с иглой» — не вольты и не секунды
                by_key.setdefault(key, unit)
    return by_key, by_name


def lookup(written: str) -> Unit | None:
    """Единица по написанию в тексте («граммов» → г)."""
    return _registry()[0].get(unit_key(written))


def canonical(name: str | None) -> Unit | None:
    """Единица характеристики по её каноническому имени («г/м²»)."""
    if not name:
        return None
    by_key, by_name = _registry()
    return by_name.get(name) or by_key.get(unit_key(name))


def convert(value: float, src: Unit, dst: Unit) -> float | None:
    """Перевод между единицами одной величины; «шт» и любая счётная («лист», «пара») взаимозаменяемы."""
    if src.dim == dst.dim:
        return round(value * src.factor / dst.factor, 6)
    if src.dim.startswith("count") and dst.dim.startswith("count") and "шт" in (src.name, dst.name):
        return value
    return None
