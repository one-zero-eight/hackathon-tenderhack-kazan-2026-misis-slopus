"""Единицы измерения: распознавание написания и приведение к единице характеристики.

«80 грамм» для плотности → 80 г/м² (контекстный синоним характеристики),
«1,2 м» для ширины в мм → 1200 мм (перевод внутри одной величины).
"""

from __future__ import annotations

from dataclasses import dataclass
from functools import lru_cache

from .text import _parse


@dataclass(frozen=True)
class Unit:
    name: str  # каноническое написание: «мм», «г/м²»
    dim: str  # величина: length, mass, …
    factor: float  # множитель к базовой единице величины


# Каноническое имя, величина, множитель, написания (без точек, в любом падеже — лемматизируются).
